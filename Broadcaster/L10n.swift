import Foundation
import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable {
    case pl, en, de, fr, es, it, pt, ru, tr

    var id: String { rawValue }

    var nativeName: String {
        switch self {
        case .pl: return "Polski"
        case .en: return "English"
        case .de: return "Deutsch"
        case .fr: return "Français"
        case .es: return "Español"
        case .it: return "Italiano"
        case .pt: return "Português"
        case .ru: return "Русский"
        case .tr: return "Türkçe"
        }
    }

    static func resolveSystem() -> AppLanguage {
        let code = Locale.current.language.languageCode?.identifier ?? "en"
        return AppLanguage(rawValue: code) ?? .en
    }
}

@MainActor
final class LanguageStore: ObservableObject {
    static let shared = LanguageStore()

    @Published private(set) var language: AppLanguage
    private nonisolated(unsafe) static var current = AppLanguage.resolveSystem()

    private init() {
        language = AppLanguage.resolveSystem()
        Self.current = language
    }

    func set(_ language: AppLanguage) {
        self.language = language
        Self.current = language
    }

    nonisolated static func text(_ key: String) -> String {
        L10n.text(key, current)
    }

    func t(_ key: String) -> String {
        L10n.text(key, language)
    }

    func t(_ key: String, _ value: Int) -> String {
        String(format: t(key), value)
    }
}

